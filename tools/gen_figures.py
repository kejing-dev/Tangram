"""Generate app/src/main/java/io/embodit/tangramwood/domain/Figures.kt from the factory design package.

The 15 figures (content.figuresExact + figureMeta + groups) are imported verbatim (D28: the build station never
composes puzzles or copy). Usage:

    python -I tools/gen_figures.py <factory>/apps/tangram-wood/design-package.json
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "app", "src", "main", "java", "io", "embodit", "tangramwood", "domain", "Figures.kt")


def kstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def num(v) -> str:
    f = float(v)
    s = repr(round(f, 6))
    return s + "f" if "." in s or "e" in s else s + ".0f"


def main(path: str) -> None:
    d = json.load(open(path, encoding="utf-8"))
    c = d["content"]
    groups = c["groups"]
    meta = c["figureMeta"]
    exact = c["figuresExact"]
    order = sorted(meta.keys(), key=lambda k: ([g["id"] for g in groups].index(meta[k]["group"]), meta[k]["order"]))
    lines = []
    w = lines.append
    w("package io.embodit.tangramwood.domain")
    w("")
    w("// GENERATED by tools/gen_figures.py from the factory design package (content.figuresExact / figureMeta / groups).")
    w("// Do not edit by hand: the build station imports the designer's puzzles and copy verbatim (D28).")
    w("")
    w("object Figures {")
    w("    val GROUPS: List<Group> = listOf(")
    for g in groups:
        w(f"        Group({kstr(g['id'])}, {kstr(c['groupNames'][g['id']]['zh'])}, {kstr(c['groupNames'][g['id']]['en'])}, {kstr(g['tipZh'])}, {kstr(g['tipEn'])}),")
    w("    )")
    w("")
    w("    val ALL: List<Figure> = listOf(")
    for fid in order:
        m = meta[fid]
        slots = []
        for s in exact[fid]:
            verts = ", ".join(f"V2({num(x)}, {num(y)})" for x, y in s["verts"])
            slots.append(f"Slot(Kind.{s['piece'].upper() if s['piece'] != 'Sq' else 'SQ'}, listOf({verts}))")
        w(f"        Figure(")
        w(f"            id = {kstr(fid)}, group = {kstr(m['group'])}, order = {m['order']}, difficulty = {m['difficulty']},")
        w(f"            nameZh = {kstr(m['nameZh'])}, nameEn = {kstr(m['nameEn'])}, sloganZh = {kstr(m['sloganZh'])}, sloganEn = {kstr(m['sloganEn'])},")
        w(f"            color = 0xFF{m['color'].lstrip('#').upper()}L,")
        w(f"            slotVerts = listOf(")
        for s in slots:
            w(f"                {s},")
        w(f"            ),")
        w(f"        ),")
    w("    )")
    w("")
    w("    fun byId(id: String): Figure? = ALL.firstOrNull { it.id == id }")
    w("}")
    w("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)}: {len(order)} figures")


if __name__ == "__main__":
    main(sys.argv[1])
